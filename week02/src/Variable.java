public class Variable {
    public static void main(String[] args) {
        int myVar;
        myVar = 100;
        myVar = myVar + 10;
        
        double myVar1 = 200.005;
        myVar1 = myVar1 * 2;

        System.out.println("Value of myVar is: " + myVar);
        System.out.println("Value of myVar1 is: "+ myVar1);
    }
}