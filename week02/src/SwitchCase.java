public class SwitchCase{

    public static void main(String[] args) {
      int  x = 'b';
        switch (x) {
            case 'b':
                System.out.println("Bangladesh");
                break;
                case 'c':
                    System.out.println("USA");
                break;
                default:
                    System.out.println("Out of earth");
                break;
        }
    }
}